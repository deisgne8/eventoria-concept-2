(() => {
  const card=document.querySelector('.proof-project-feature');
  if(!card||matchMedia('(max-width:1024px), (prefers-reduced-motion:reduce)').matches)return;
  const makeLayer=(className,src,word)=>{
    const layer=document.createElement('div');
    layer.className=className;
    layer.setAttribute('aria-hidden','true');
    layer.innerHTML='<img src="'+src+'" alt=""><div class="proof-next-letters" aria-hidden="true">'+[...word].filter(letter=>letter!==' ').map(letter=>`<span>${letter}</span>`).join('')+'</div>';
    card.querySelector('.proof-project-image').append(layer);
    return layer;
  };
  const next=makeLayer('proof-next-image','assets/unsplash/proof-production.jpg','PRODUCTION');
  const nextDetails=document.createElement('div');
  nextDetails.className='proof-next-details';
  nextDetails.innerHTML='<h3>Visible practical plan</h3><p>The creative and operational details stay connected from sketch to show.</p>';
  next.append(nextDetails);
  const third=makeLayer('proof-next-image proof-third-image','assets/unsplash/proof-live.jpg','LIVE DELIVERY');
  const thirdDetails=document.createElement('div');
  thirdDetails.className='proof-third-details';
  thirdDetails.innerHTML='<h3>Calm on-site delivery</h3><p>One team carries the work through the live moment and final cue.</p>';
  third.append(thirdDetails);
  const details=document.createElement('div');
  details.className='proof-first-details';
  details.innerHTML='<h3>Clear creative direction</h3><p>Every decision has a reason, rooted in the occasion and the audience.</p>';
  card.querySelector('.proof-project-image').append(details);
  const update=()=>{
    const rect=card.getBoundingClientRect();
    const travel=Math.max(1,card.offsetHeight-innerHeight);
    const phase=Math.max(0,Math.min(1,-rect.top/travel))*3;
    const clamp=value=>Math.max(0,Math.min(1,value));
    const progress=clamp(phase/.25);
    const nextImageProgress=clamp((phase-1)/.5);
    const nextLetterProgress=clamp((phase-1.5)/.25);
    const thirdImageProgress=clamp((phase-2)/.5);
    const thirdLetterProgress=clamp((phase-2.5)/.25);
    card.style.setProperty('--letter-progress',progress);
    next.style.setProperty('--next-image-progress',nextImageProgress);
    next.style.setProperty('--next-letter-progress',nextLetterProgress);
    next.classList.toggle('is-assembled',nextLetterProgress>=.98);
    third.style.setProperty('--next-image-progress',thirdImageProgress);
    third.style.setProperty('--next-letter-progress',thirdLetterProgress);
    third.classList.toggle('is-assembled',thirdLetterProgress>=.98);
    card.classList.toggle('is-pinned',rect.top<=0&&rect.bottom>=innerHeight);
    card.classList.toggle('is-assembled',progress>=.98);
  };
  addEventListener('scroll',update,{passive:true});
  addEventListener('resize',update);
  update();
})();
